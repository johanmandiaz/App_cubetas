def get_connection(with_db=True):
    config = {
        "host": DB_HOST,
        "user": DB_USER,
        "password": DB_PASSWORD,
        "cursorclass": pymysql.cursors.DictCursor
    }
    if with_db:
        config["database"] = DB_NAME
    return pymysql.connect(**config)

def inicializar_bd():
    # Crear la base de datos si no existe
    conexion = get_connection(with_db=False)
    with conexion.cursor() as cursor:
        cursor.execute(f"CREATE DATABASE IF NOT EXISTS {DB_NAME}")
    conexion.commit()
    conexion.close()

    # Crear la tabla principal de Kardex
    conexion = get_connection()
    with conexion.cursor() as cursor:
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS kardex_cubetas (
                id INT AUTO_INCREMENT PRIMARY KEY,
                fecha DATE NOT NULL,
                transportista VARCHAR(100) NOT NULL,
                cliente VARCHAR(100) NOT NULL,
                zona VARCHAR(100) NOT NULL,
                entregadas INT DEFAULT 0,
                retornadas INT DEFAULT 0,
                pendientes INT DEFAULT 0,
                fecha_registro TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            );
        """)
    conexion.commit()
    conexion.close()

