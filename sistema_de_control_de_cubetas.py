@app.route("/")
def index():
    try:
        inicializar_bd()
    except Exception as e:
        return f"Error conectando a la BD. Verifica credenciales y el Security Group en AWS. Detalle: {e}"

    conexion = get_connection()
    fecha_hoy = datetime.now().strftime('%Y-%m-%d')

    with conexion.cursor() as cursor:
        # 1. Obtener últimos movimientos
        cursor.execute("SELECT * FROM kardex_cubetas ORDER BY id DESC LIMIT 20")
        movimientos = cursor.fetchall()

        # 2. Obtener consolidado por Zona
        cursor.execute("""
            SELECT zona, SUM(pendientes) as total_pendientes
            FROM kardex_cubetas
            GROUP BY zona
            ORDER BY total_pendientes DESC
        """)
        resumen_zonas = cursor.fetchall()

        # 3. Obtener consolidado por Cliente
        cursor.execute("""
            SELECT cliente, zona, SUM(pendientes) as total_pendientes
            FROM kardex_cubetas
            GROUP BY cliente, zona
            HAVING total_pendientes != 0
            ORDER BY total_pendientes DESC
        """)
        resumen_clientes = cursor.fetchall()

    conexion.close()

    return render_template_string(
        html_template,
        movimientos=movimientos,
        resumen_zonas=resumen_zonas,
        resumen_clientes=resumen_clientes,
        fecha_hoy=fecha_hoy
    )

@app.route("/guardar", methods=["POST"])
def guardar_registro():
    fecha = request.form["fecha"]
    transportista = request.form["transportista"]
    cliente = request.form["cliente"]
    zona = request.form["zona"]
    entregadas = int(request.form["entregadas"])
    retornadas = int(request.form["retornadas"])

    # Lógica de Supply Chain: Las cubetas pendientes que quedan en deuda en esta transacción
    pendientes = entregadas - retornadas

    conexion = get_connection()
    with conexion.cursor() as cursor:
        cursor.execute("""
            INSERT INTO kardex_cubetas (fecha, transportista, cliente, zona, entregadas, retornadas, pendientes)
            VALUES (%s, %s, %s, %s, %s, %s, %s)
        """, (fecha, transportista, cliente, zona, entregadas, retornadas, pendientes))
    conexion.commit()
    conexion.close()

    return redirect(url_for("index"))

